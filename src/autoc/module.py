class Source(_EntityContainer, _SmartRenderer):
  def __init__(self, module, index, *args, **kws):
    super().__init__(*args, **kws)
    self.module = module
    self.complexity = 0
    self.index = index
    self.__digest = None
    self.__stream = None

  @property
  def file_name(self):
    if self.module.source_count < 2:
      return f"{self.module.name}_auto.c"
    return f"{self.module.name}_auto{self.index}.c"

  @property
  def digest(self): return self.__digest

  @property
  def stream(self):
    if self.__stream is None:
      self.__stream = _StreamFile(self.file_name + "~")
    return self.__stream

  def add(self, entity):
    if entity not in self.entities:
      self.complexity += entity.complexity
    self.entities.add(entity)
    return self

  def render_contents(self, stream):
    self.render_prologue(stream)
    total_entities = set()
    for e in self.entities:
      total_entities.update(e.total_references)
    for e in sorted(total_entities):
      for line in e.forward_declarations():
        stream.write(line)
    for e in sorted(self.entities):
      for line in e.implementation():
        stream.write(line)

  def render_prologue(self, stream):
    stream.write(f"""
      {_caption}
      #include "{self.module.header.file_name}"
    """.lstrip())


