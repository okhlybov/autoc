import os
import re
import hashlib
import autoc


_caption = f"/* Automagically generated by autoc {autoc.__version__} */"


class _EntityContainer:
  def __init__(self, *args, **kws):
    super().__init__(*args, **kws)
    self.entities = set()

  def add(self, entity):
    self.entities.add(entity)
    return self


class _Builder(list):
  def __init__(self, *args, **kws):
    super().__init__(*args, **kws)
    self.complexity = 0

  def append(self, obj):
    s = str(obj)
    self.complexity += len(s)
    super().append(s)


